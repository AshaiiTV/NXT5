export function redirectRules(privatePaths, dynamicPaths) {
  return [
    "# Generated by tools/prerender.mjs from public metadata and application routes.",
    // Exact production alias only: previews keep their own URLs and noindex.
    // With no query matcher/target, Netlify passes the original query through.
    `https://nxt5.netlify.app/* ${SITE_ORIGIN}/:splat 301!`,
    `http://nxt5.netlify.app/* ${SITE_ORIGIN}/:splat 301!`,
    "/index.html / 301!",
    "/inscription /creer-un-compte 301!",
    // Keep old team bookmarks and invitation queries on the canonical app route.
    "/equipes /mon-equipe 301!",
    "/equipes/ /mon-equipe 301!",
    ...Object.keys(PUBLIC_METADATA).filter(path => path !== "/").map(path => `${path}.html ${path} 301!`),
    ...privatePaths.filter(path => path !== "/inscription").flatMap(path => [`${path} /${shellFor(path)} 200`, `${path}/ /${shellFor(path)} 200`]),
    ...dynamicPaths.map(path => `${path}/* /${shellFor(path)} 200`),
    ...RETIRED_BRAND_ASSETS.map(([from, to]) => `${from} ${to} 200`),
    // Existing CDN assets and Netlify Functions are not shadowed (no force flag).
    "/* /404.html 404",
    "",
  ].join("\n");
}

export function robotsHeaders(config, privatePaths, dynamicPaths) {
  if (config.noindex) return "/*\n  X-Robots-Tag: noindex, follow\n";
  return [...new Set([...shellFiles().map(([file]) => `/${file}`), "/404.html", "/404", ...privatePaths.flatMap(path => [path, `${path}/`]), ...dynamicPaths.map(path => `${path}/*`)])]
    .map(path => `${path}\n  X-Robots-Tag: noindex, follow\n`).join("\n");
}
